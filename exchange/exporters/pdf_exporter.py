"""Printable PDF timetable and summary document generator using ReportLab.

Produces landscape schedules with header branding, cell text wrapping,
multi-page tables with repeated headers, and draft/conflict indicators.
"""

from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch, mm
from reportlab.platypus import (
    HRFlowable,
    KeepTogether,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from core.models import ScheduledSession
from exchange.models import (
    ConflictReportRow,
    ExportFormat,
    ExportResult,
    TimetableLayout,
)
from exchange.security import validate_export_file_path

DAY_NAMES = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]


class NumberedCanvas:
    """Canvas that performs a two-pass calculation for 'Page X of Y' footers."""

    def __init__(self, *args: Any, **kwargs: Any):
        self._saved_page_states: List[Any] = []

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            super().showPage()
        super().save()

    def draw_page_number(self, page_count: int) -> None:
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#595959"))
        footer_text = f"Page {self._pageNumber} of {page_count}  |  Generated by Timetable Thingy"
        self.drawRightString(297 * mm - 15 * mm, 10 * mm, footer_text)
        self.restoreState()


class PDFTimetableExporter:
    """Generates publication-quality printable PDF timetables."""

    @classmethod
    def export_timetable(
        cls,
        output_path: str | Path,
        sessions: List[ScheduledSession],
        layout: TimetableLayout = TimetableLayout.CLASS_GRID,
        metadata: Optional[Dict[str, Any]] = None,
        conflicts: Optional[List[ConflictReportRow]] = None,
    ) -> ExportResult:
        dest = validate_export_file_path(output_path, expected_ext=".pdf")
        meta = metadata or {}

        # Landscape A4 (297 x 210 mm)
        doc = SimpleDocTemplate(
            str(dest),
            pagesize=landscape(A4),
            leftMargin=12 * mm,
            rightMargin=12 * mm,
            topMargin=12 * mm,
            bottomMargin=15 * mm,
        )

        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=16,
            leading=20,
            textColor=colors.HexColor("#1F4E79"),
        )
        subtitle_style = ParagraphStyle(
            "DocSubtitle",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=10,
            leading=13,
            textColor=colors.HexColor("#333333"),
        )
        badge_draft_style = ParagraphStyle(
            "BadgeDraft",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=9,
            leading=11,
            textColor=colors.HexColor("#C00000"),
            alignment=2,  # Right-aligned
        )
        badge_pub_style = ParagraphStyle(
            "BadgePub",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=9,
            leading=11,
            textColor=colors.HexColor("#2E75B6"),
            alignment=2,
        )
        grid_header_style = ParagraphStyle(
            "GridHeader",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=8,
            leading=10,
            alignment=1,  # Center
            textColor=colors.HexColor("#FFFFFF"),
        )
        day_label_style = ParagraphStyle(
            "DayLabel",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=8,
            leading=10,
            alignment=1,
            textColor=colors.HexColor("#1F4E79"),
        )
        cell_bold_style = ParagraphStyle(
            "CellBold",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=7.5,
            leading=9,
            alignment=1,
            textColor=colors.HexColor("#000000"),
        )
        cell_sub_style = ParagraphStyle(
            "CellSub",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=6.5,
            leading=8,
            alignment=1,
            textColor=colors.HexColor("#333333"),
        )
        empty_cell_style = ParagraphStyle(
            "CellEmpty",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=7,
            leading=8,
            alignment=1,
            textColor=colors.HexColor("#A6A6A6"),
        )

        elements: List[Any] = []

        institution_name = meta.get("institution_name", "Academic Institution")
        dept_name = meta.get("department_name", "All Departments")
        academic_year = meta.get("academic_year_name", "2026-2027")
        semester_name = meta.get("semester_name", "Odd Semester")
        timetable_name = meta.get("timetable_name", "Weekly Timetable")
        version = meta.get("version", 1)
        is_published = meta.get("is_published", False)
        status_label = "PUBLISHED SCHEDULE" if is_published else f"DRAFT (v{version})"
        badge_style = badge_pub_style if is_published else badge_draft_style

        days = meta.get("days", [0, 1, 2, 3, 4])
        periods_per_day = meta.get("periods_per_day", 6)
        period_times = meta.get("period_times", [])  # list of (start_str, end_str)

        class_name_map = meta.get("class_name_map", {})
        sub_code_map = meta.get("sub_code_map", {})
        sub_name_map = meta.get("sub_name_map", {})
        teacher_emp_map = meta.get("teacher_emp_map", {})
        teacher_name_map = meta.get("teacher_name_map", {})
        room_code_map = meta.get("room_code_map", {})

        # Grouping key depends on layout
        if layout == TimetableLayout.TEACHER_GRID:
            group_key_func = lambda s: s.teacher_id
            get_title_func = lambda k: f"Faculty: {teacher_name_map.get(k, k)} ({teacher_emp_map.get(k, '')})"
        elif layout == TimetableLayout.ROOM_GRID:
            group_key_func = lambda s: s.room_id
            get_title_func = lambda k: f"Room: {room_code_map.get(k, k)}"
        else:  # CLASS_GRID default
            group_key_func = lambda s: s.class_group_id
            get_title_func = lambda k: f"Class / Section: {class_name_map.get(k, k)}"

        grouped: Dict[str, List[ScheduledSession]] = {}
        for s in sessions:
            k = group_key_func(s)
            grouped.setdefault(k, []).append(s)

        if not grouped:
            # Handle empty schedule
            header_table = Table(
                [[
                    Paragraph(f"<b>{institution_name}</b> - {timetable_name}", title_style),
                    Paragraph(status_label, badge_style),
                ]],
                colWidths=[200 * mm, 70 * mm],
            )
            elements.append(header_table)
            elements.append(Spacer(1, 15 * mm))
            elements.append(Paragraph("No scheduled sessions exist for this timetable.", subtitle_style))
            doc.build(elements)
            return ExportResult(
                success=True,
                format=ExportFormat.PDF,
                file_path=str(dest),
                file_size_bytes=dest.stat().st_size,
                records_exported=0,
                message=f"Exported empty timetable to {dest.name}.",
            )

        entity_keys = sorted(grouped.keys())

        for idx, e_key in enumerate(entity_keys):
            entity_title = get_title_func(e_key)
            e_sessions = grouped[e_key]

            # Header Banner
            now_str = datetime.now().strftime("%Y-%m-%d %H:%M")
            header_data = [
                [
                    Paragraph(f"<b>{institution_name}</b>", title_style),
                    Paragraph(status_label, badge_style),
                ],
                [
                    Paragraph(
                        f"Department: {dept_name}  |  Session: {academic_year} ({semester_name})<br/>"
                        f"<b>{entity_title}</b>",
                        subtitle_style,
                    ),
                    Paragraph(f"Generated: {now_str}", subtitle_style),
                ],
            ]
            banner_table = Table(header_data, colWidths=[195 * mm, 75 * mm])
            banner_table.setStyle(TableStyle([
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
                ("TOPPADDING", (0, 0), (-1, -1), 0),
            ]))
            elements.append(banner_table)
            elements.append(Spacer(1, 3 * mm))
            elements.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#1F4E79"), spaceAfter=4))

            # Build matrix: (day, period) -> content paragraphs
            matrix: Dict[tuple[int, int], List[Any]] = {}
            for s in e_sessions:
                for offset in range(s.duration_periods):
                    slot = (s.day_of_week, s.start_period + offset)
                    s_code = sub_code_map.get(s.class_group_id, "SUB")
                    s_name = sub_name_map.get(s.class_group_id, "")
                    t_name = teacher_name_map.get(s.teacher_id, "") or teacher_emp_map.get(s.teacher_id, "")
                    r_code = room_code_map.get(s.room_id, "")
                    c_name = class_name_map.get(s.class_group_id, "")

                    cell_elements = []
                    cell_elements.append(Paragraph(f"<b>{s_code}</b>", cell_bold_style))
                    if layout == TimetableLayout.CLASS_GRID:
                        cell_elements.append(Paragraph(f"{t_name} | {r_code}", cell_sub_style))
                    elif layout == TimetableLayout.TEACHER_GRID:
                        cell_elements.append(Paragraph(f"{c_name} | {r_code}", cell_sub_style))
                    else:  # ROOM_GRID
                        cell_elements.append(Paragraph(f"{c_name} | {t_name}", cell_sub_style))

                    matrix.setdefault(slot, []).extend(cell_elements)

            # Table Header Row: Day | Period 1 (Time) | Period 2 ...
            header_row: List[Any] = [Paragraph("Day / Period", grid_header_style)]
            col_width_available = 245 * mm  # Total width for periods
            period_col_width = col_width_available / periods_per_day
            col_widths = [25 * mm] + [period_col_width] * periods_per_day

            for p in range(periods_per_day):
                time_str = ""
                if p < len(period_times):
                    time_str = f"<br/><font size='5.5'>{period_times[p][0]}-{period_times[p][1]}</font>"
                header_row.append(Paragraph(f"Period {p + 1}{time_str}", grid_header_style))

            table_rows = [header_row]

            # Data rows
            for d in days:
                d_name = DAY_NAMES[d] if 0 <= d < len(DAY_NAMES) else f"Day {d}"
                row_cells: List[Any] = [Paragraph(f"<b>{d_name}</b>", day_label_style)]

                for p in range(periods_per_day):
                    slot_elements = matrix.get((d, p), [])
                    if slot_elements:
                        row_cells.append(slot_elements)
                    else:
                        row_cells.append(Paragraph("—", empty_cell_style))

                table_rows.append(row_cells)

            grid_table = Table(table_rows, colWidths=col_widths, repeatRows=1)
            t_style = [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1F4E79")),
                ("BACKGROUND", (0, 1), (0, -1), colors.HexColor("#F2F4F7")),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#B0C4DE")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LEFTPADDING", (0, 0), (-1, -1), 2),
                ("RIGHTPADDING", (0, 0), (-1, -1), 2),
            ]
            grid_table.setStyle(TableStyle(t_style))
            elements.append(grid_table)

            # Footer conflicts notice if applicable
            if conflicts and len(conflicts) > 0:
                elements.append(Spacer(1, 3 * mm))
                c_msg = f"<b>Notice:</b> This draft schedule has {len(conflicts)} detected constraints or preference warnings."
                elements.append(Paragraph(c_msg, subtitle_style))

            # Page break between entities except on last entity
            if idx < len(entity_keys) - 1:
                elements.append(PageBreak())

        doc.build(elements)

        return ExportResult(
            success=True,
            format=ExportFormat.PDF,
            file_path=str(dest),
            file_size_bytes=dest.stat().st_size,
            records_exported=len(sessions),
            message=f"Exported printable PDF with {len(entity_keys)} schedules to {dest.name}.",
        )
